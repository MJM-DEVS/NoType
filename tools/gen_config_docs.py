"""Generate docs/configuration.md from DEFAULT_CONFIG in config.py.

Reads config.py as source (ast + tokenize) instead of importing it, so it has
no side effects (importing config.py creates the user-data folder) and runs on
any platform. Each key's description is the comment on its line in config.py;
keys without one take theirs from NOTES below. A value that spans several
lines collects the comments on all of them.

  python tools/gen_config_docs.py           # rewrite docs/configuration.md
  python tools/gen_config_docs.py --check   # exit 1 if it is out of date

Build/docs helper, not runtime code.
"""

import ast
import io
import json
import os
import sys
import tokenize

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
CONFIG_PY = os.path.join(ROOT, "config.py")
DOC = os.path.join(ROOT, "docs", "configuration.md")

# Descriptions for keys that have no comment in config.py.
NOTES = {
    "model_size": "Speech model id from the catalog in transcriber.py / electron/model-catalog.js "
                  "(tiny, base, small, medium, large-v2, large-v3, large-v3-turbo, "
                  "distil-large-v3, distil-large-v3.5, german-turbo)",
    "hotkey": "Dictation hotkey",
    "autostart": "Start with Windows. The Electron app treats the Windows login item as the source of truth",
    "overlay_enabled": "Currently has no effect: nothing reads it",
    "command_hotkey": "Command mode hotkey",
    "agent_hotkey": "Agent hotkey (only registered while `agent_enabled` is on)",
    "agent_url": "http(s) URL the agent hotkey POSTs to; empty = not set up",
    "first_run_complete": "False opens the setup guide on start",
}

# Keys the app reads or writes that have no entry in DEFAULT_CONFIG. Kept by
# hand: --check cannot notice when one of these changes in the code.
OTHER_KEYS = [
    ("languages", "unset",
     ("The languages the user speaks with optional shares, "
      "`[{\"code\": \"de\", \"share\": 80}, ...]`. Without it, `language` counts at 100 %")),
    ("overlay_theme", "unset (= `system`)",
     "Design: `dark`, `light` (Sage) or `system` (follow Windows). Electron only"),
    ("compute_type", "`auto` (backend)",
     ("faster-whisper compute type (CUDA: int8_float16, float16, int8; CPU: int8, float32). "
      "The backend persists a working fallback here after a cuBLAS refusal")),
    ("beam_size", "`auto` (backend)", "Beam size for the final pass, `auto` or a number"),
    ("vad_sensitivity", "`300` (backend)", "Minimum silence in ms the VAD needs to split speech"),
    ("mic_device_index", "unset",
     "Legacy (up to 2.9): PortAudio index, migrated to `mic_device_name` on start"),
]

HEADER = """\
# Configuration reference

<!-- Generated by tools/gen_config_docs.py from DEFAULT_CONFIG in config.py. Do not edit by hand. -->

NoType keeps its settings in `settings.json` in the user-data folder: `%APPDATA%\\NoType\\` on Windows, `$XDG_CONFIG_HOME/NoType/` (or `~/.config/NoType/`) elsewhere. Both the Electron app and the Python backend read and write this file; the settings window is the normal way to change it. Keys missing from the file fall back to the defaults below.

Regenerate this page after changing `DEFAULT_CONFIG`:

```bash
python tools/gen_config_docs.py           # rewrite this file
python tools/gen_config_docs.py --check   # exit 1 if it is out of date
```

## Keys in `DEFAULT_CONFIG`

| Key | Default | Meaning |
|---|---|---|
"""

FOOTER_INTRO = """
## Other keys

These are read or written by the app but have no default in `DEFAULT_CONFIG`. This list is kept by hand in `tools/gen_config_docs.py`.

| Key | Default | Meaning |
|---|---|---|
"""

FOOTER_NOTE = """
`electron/main.js` (`loadConfig`) has its own fallback defaults for when it reads the file; the setup guide writes the user's choices on first run.
"""


def _cell(text: str) -> str:
    return text.replace("|", "\\|").strip()


def _comments(source: str) -> dict:
    """Line number -> text of the comment on that line."""
    out = {}
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            out[tok.start[0]] = tok.string.lstrip("#").strip()
    return out


def read_defaults(source: str) -> list:
    """[(key, default, comment)] in the order of DEFAULT_CONFIG."""
    tree = ast.parse(source)
    for node in tree.body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and node.targets[0].id == "DEFAULT_CONFIG"
                and isinstance(node.value, ast.Dict)):
            comments = _comments(source)
            rows = []
            for key, value in zip(node.value.keys, node.value.values):
                name = ast.literal_eval(key)
                text = " ".join(comments[n] for n in range(key.lineno, value.end_lineno + 1)
                                if n in comments)
                rows.append((name, ast.literal_eval(value), text))
            return rows
    raise SystemExit("DEFAULT_CONFIG not found in config.py")


def render(source: str) -> str:
    lines = [HEADER]
    for name, default, comment in read_defaults(source):
        meaning = comment or NOTES.get(name, "")
        value = _cell(json.dumps(default, ensure_ascii=False))
        lines.append(f"| `{name}` | `{value}` | {_cell(meaning)} |\n")
    lines.append(FOOTER_INTRO)
    for name, default, meaning in OTHER_KEYS:
        lines.append(f"| `{name}` | {default} | {_cell(meaning)} |\n")
    lines.append(FOOTER_NOTE)
    return "".join(lines)


def main(argv: list) -> int:
    with open(CONFIG_PY, encoding="utf-8") as f:
        expected = render(f.read())
    if "--check" in argv:
        try:
            with open(DOC, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != expected:
            print("docs/configuration.md is out of date; run: python tools/gen_config_docs.py")
            return 1
        print("docs/configuration.md is up to date")
        return 0
    os.makedirs(os.path.dirname(DOC), exist_ok=True)
    with open(DOC, "w", encoding="utf-8", newline="\n") as f:
        f.write(expected)
    print(f"Wrote {os.path.relpath(DOC, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
